import os
import shutil
from fastapi import FastAPI, UploadFile, File, HTTPException
from fastapi.responses import JSONResponse
from backend.inference import load_aetherdx_model, run_inference

# Create FastAPI app
app = FastAPI(
    title="XAI-COMPASS — AetherDx Model Connector API",
    description="API interface for integrating the existing AetherDx healthcare AI model with the XAI-COMPASS explainability and governance platform. The underlying model is used without modification.",
    version="1.0.0"
)

# Global model variable
model = None

@app.on_event("startup")
async def startup_event():
    global model
    try:
        print("Loading AetherDx model...")
        model_path = os.path.join("models", "Inception_friend_version.keras")
        model = load_aetherdx_model(model_path)
        print("Model loaded successfully.")
    except Exception as e:
        print(f"Error loading model: {e}")
        # We don't crash startup to let the /health endpoint indicate failure, 
        # or we could let it crash. Standard is to let it crash if model is required.
        raise RuntimeError(f"Could not load the model: {e}")

@app.get("/health", summary="Health Check", description="Checks the health and status of the model connector.")
async def health_check():
    """
    Returns the health status of the API and details about the connected model.
    """
    if model is None:
        return JSONResponse(status_code=503, content={"status": "error", "message": "Model not loaded"})
    
    return {
        "status": "ok",
        "service": "XAI-COMPASS Model Connector",
        "model": "AetherDx InceptionV3",
        "domain": "Healthcare",
        "integration": "Existing AI Model"
    }

@app.post("/predict", summary="Predict Nail Disease", description="Accepts a nail image and returns the prediction generated by the existing AetherDx healthcare model. The underlying trained model is not modified by this API.")
async def predict_image(file: UploadFile = File(...)):
    if not file:
        raise HTTPException(status_code=400, detail="No file uploaded.")
    
    # Validate file extension
    valid_extensions = [".jpg", ".jpeg", ".png"]
    ext = os.path.splitext(file.filename)[1].lower()
    if ext not in valid_extensions:
        raise HTTPException(status_code=400, detail=f"Unsupported image format. Allowed formats: {', '.join(valid_extensions)}")
    
    if model is None:
        raise HTTPException(status_code=503, detail="Model is currently unavailable.")
        
    temp_dir = "outputs"
    os.makedirs(temp_dir, exist_ok=True)
    temp_image_path = os.path.join(temp_dir, f"api_temp_{file.filename}")
    
    try:
        # Save the uploaded file temporarily
        with open(temp_image_path, "wb") as buffer:
            shutil.copyfileobj(file.file, buffer)
            
        # Run inference using the existing logic
        result = run_inference(model, temp_image_path)
        
        # Human-readable mapping (for display only)
        label_mapping = {
            "Healthy": "Healthy",
            "Liver_disease": "Liver Disease",
            "Psoriasis_disease": "Psoriasis"
        }
        internal_pred = result["prediction"]
        display_pred = label_mapping.get(internal_pred, internal_pred)
        
        return {
            "prediction": internal_pred,
            "display_prediction": display_pred,
            "probability": result["confidence"],
            "model": "AetherDx InceptionV3",
            "model_file": "Inception_friend_version.keras",
            "domain": "Healthcare",
            "integration": "Existing AI Model",
            "xai_available": True
        }
        
    except Exception as e:
        raise HTTPException(status_code=500, detail="Model inference failed.")
    finally:
        # Cleanup temporary file
        if os.path.exists(temp_image_path):
            try:
                os.remove(temp_image_path)
            except:
                pass
